export function validateDiscountCode(rawCode: string, usedCodes: string[] = []): {
  valid: boolean;
  discountPercent?: number;
  appliesTo?: 'all' | 'conf_only' | 'preconf_only';
  code?: string;
  message: string;
} {
  const code = (rawCode || '').trim().toUpperCase();
  if (!code) {
    return { valid: false, message: 'Please enter a discount code.' };
  }

  const is100 = CONFERENCE_100_CODES.includes(code);
  const is10 = ALL_10_DISCOUNT_CODES.includes(code);

  if (!is100 && !is10) {
    return { valid: false, message: 'Invalid discount code.' };
  }

  const upperUsedCodes = usedCodes.map((c) => (c || '').toUpperCase());
  if (upperUsedCodes.includes(code)) {
    return { valid: false, message: 'This code has already been used. Each code is valid for one-time use only.' };
  }

  if (is100) {
    return {
      valid: true,
      discountPercent: 100,
      appliesTo: 'conf_only',
      code,
      message: 'Code applied! 100% discount added to Conference fees.'
    };
  }

  return {
    valid: true,
    discountPercent: 10,
    appliesTo: 'preconf_only',
    code,
    message: 'Code applied! 10% discount added to Pre-Conference fees.'
  };
}
